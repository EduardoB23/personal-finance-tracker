-- Schema inicial gerenciado pelo Flyway (D12). Valores monetários em NUMERIC(19,2).

CREATE TABLE profiles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE categories (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    type     VARCHAR(20)  NOT NULL,
    archived BOOLEAN DEFAULT FALSE NOT NULL,
    -- O H2 não aceita índice sobre expressão; a coluna gerada garante unicidade sem diferenciar maiúsculas
    name_key VARCHAR(100) GENERATED ALWAYS AS (LOWER(name)),
    CONSTRAINT uk_categories_name_type UNIQUE (name_key, type)
);

CREATE TABLE bank_accounts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255)   NOT NULL,
    type    VARCHAR(30)    NOT NULL,
    balance NUMERIC(19, 2) NOT NULL
);

CREATE TABLE credit_cards (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255)   NOT NULL,
    limit_amount    NUMERIC(19, 2) NOT NULL,
    available_limit NUMERIC(19, 2) NOT NULL,
    closing_day     INTEGER        NOT NULL,
    due_day         INTEGER        NOT NULL
);

CREATE TABLE credit_card_invoices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_card_id BIGINT         NOT NULL REFERENCES credit_cards (id),
    billing_month  VARCHAR(7)     NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    due_date       DATE           NOT NULL,
    CONSTRAINT uk_invoices_card_month UNIQUE (credit_card_id, billing_month)
);

CREATE TABLE budgets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT         NOT NULL REFERENCES categories (id),
    limit_amount NUMERIC(19, 2) NOT NULL,
    budget_month VARCHAR(7)     NOT NULL,
    CONSTRAINT uk_budgets_category_month UNIQUE (category_id, budget_month)
);

CREATE TABLE goals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(255)   NOT NULL,
    target_amount  NUMERIC(19, 2) NOT NULL,
    current_amount NUMERIC(19, 2) NOT NULL,
    profile_id     BIGINT         NOT NULL REFERENCES profiles (id)
);

CREATE TABLE transactions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                 VARCHAR(20)    NOT NULL,
    description          VARCHAR(255)   NOT NULL,
    category_id          BIGINT REFERENCES categories (id),
    amount               NUMERIC(19, 2) NOT NULL,
    "DATE"               DATE           NOT NULL,
    profile_id           BIGINT         NOT NULL REFERENCES profiles (id),
    account_id           BIGINT REFERENCES bank_accounts (id),
    target_account_id    BIGINT REFERENCES bank_accounts (id),
    credit_card_id       BIGINT REFERENCES credit_cards (id),
    recurring            BOOLEAN DEFAULT FALSE NOT NULL,
    installment_count    INTEGER,
    installment_group_id BIGINT,
    recurrence_source_id BIGINT REFERENCES transactions (id) ON DELETE SET NULL,
    CONSTRAINT uk_transactions_recurrence_date UNIQUE (recurrence_source_id, "DATE")
);

CREATE TABLE recurrence_exceptions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_transaction_id BIGINT NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    occurrence_date       DATE   NOT NULL,
    CONSTRAINT uk_recurrence_exceptions UNIQUE (source_transaction_id, occurrence_date)
);
