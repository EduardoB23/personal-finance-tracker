-- Pagamentos de fatura (D18, D34). O status da fatura é derivado destas linhas, nunca gravado.
CREATE TABLE invoice_payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT         NOT NULL REFERENCES credit_card_invoices (id),
    account_id BIGINT         NOT NULL REFERENCES bank_accounts (id),
    profile_id BIGINT         NOT NULL REFERENCES profiles (id),
    amount     NUMERIC(19, 2) NOT NULL,
    paid_on    DATE           NOT NULL
);
